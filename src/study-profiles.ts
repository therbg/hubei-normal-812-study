function intentFor(topic: string) {
  if (/生平|时代/.test(topic)) return "life";
  if (/艺术|文学价值|特质|京味|忧郁|意象/.test(topic)) return "art";
  if (/思想|内容|形象|意义/.test(topic)) return "content";
  if (/运动|诗派|小说派|文学革命|名称和由来|体诗|骈文/.test(topic)) return "definition";
  return "work";
}

function scoreFor(type: MemorizationCard["type"]) {
  return type === "名词解释" ? 5 : type === "论述题" ? 15 : 10;
}

function wordPlanFor(type: MemorizationCard["type"]) {
  if (type === "名词解释") return { standard: 420, high: 650, minutes: 7 };
  if (type === "论述题") return { standard: 900, high: 1200, minutes: 20 };
  return { standard: 650, high: 900, minutes: 12 };
}

